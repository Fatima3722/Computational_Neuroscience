import scipy.io
import numpy as np
import matplotlib.pyplot as plt
import os # Added for directory creation and path joining

# -----------------------------------------------------------------------------
# --- STEP 1: Define File Path and Analysis Parameters ---
# -----------------------------------------------------------------------------

# *** IMPORTANT: ADJUST THIS PATH TO WHERE YOUR .mat FILE IS LOCATED ***
mat_file_path = "data_monkey1_gratings.mat"

# Analysis parameters based on documentation and MATLAB script insights
analysis_window_start_time = 0.28  # seconds (stimulus effectively analyzed from 0.28s to 1.28s)
analysis_window_end_time = 1.28    # seconds
analysis_duration = analysis_window_end_time - analysis_window_start_time # Should be 1.0 second

# !!! CRITICAL ASSUMPTION / PLACEHOLDER !!!
# Assuming 12 orientations (or directions of drift) of grating,
# equally spaced from 0 to 330 degrees.
# This needs to be verified if possible from publications.
assumed_grating_orientations_degrees = np.arange(0, 360, 30) # Creates [0, 30, 60, ..., 330]

# --- Output Directory for Plots ---
output_plot_directory = "tuning_curve_plots" # Will be created in the same dir as your script
if not os.path.exists(output_plot_directory):
    os.makedirs(output_plot_directory)
    print(f"Created directory: {output_plot_directory}")

# -----------------------------------------------------------------------------
# --- STEP 2: Load Data and Extract Relevant Information ---
# -----------------------------------------------------------------------------
print(f"Attempting to load data from: {mat_file_path}")
try:
    mat_data_loaded = scipy.io.loadmat(mat_file_path)
    print("Successfully loaded .mat file.")

    if 'data' in mat_data_loaded:
        data_struct_scalar = mat_data_loaded['data'][0, 0]

        if 'EVENTS' in data_struct_scalar.dtype.names:
            events_data = data_struct_scalar['EVENTS']
            num_neurons, num_grating_conditions, num_trials_per_condition = events_data.shape

            print(f"Data extracted: {num_neurons} neurons, {num_grating_conditions} grating conditions, {num_trials_per_condition} trials per condition.")

            if num_grating_conditions != len(assumed_grating_orientations_degrees):
                print(f"WARNING: Number of grating conditions in data ({num_grating_conditions}) "
                      f"does not match assumed orientations ({len(assumed_grating_orientations_degrees)}).")
                print("Please verify the grating orientations for accurate plotting!")
        else:
            print("ERROR: 'EVENTS' field not found within the 'data' structure.")
            exit()
    else:
        print("ERROR: Top-level key 'data' not found in .mat file.")
        exit()

except FileNotFoundError:
    print(f"ERROR: File not found. Please double-check the path: {mat_file_path}")
    exit()
except Exception as e:
    print(f"An error occurred during data loading or initial processing: {e}")
    exit()

# -----------------------------------------------------------------------------
# --- STEP 3: Loop Through Neurons, Calculate Tuning Curve, and Plot/Save ---
# -----------------------------------------------------------------------------

# Decide which neurons to plot.
# Option 1: A specific subset
# neurons_to_plot_indices = [0, 1, 5, 10, 15, 20]
# Option 2: First N neurons
neurons_to_plot_indices = range(min(20, num_neurons)) # Plot first 20 neurons or all if fewer than 20
# Option 3: All neurons (can be slow if many neurons)
# neurons_to_plot_indices = range(num_neurons)

print(f"\nStarting analysis for {len(list(neurons_to_plot_indices))} selected neurons...")

for neuron_idx in neurons_to_plot_indices:
    if neuron_idx >= num_neurons:
        print(f"Skipping neuron_idx {neuron_idx} as it is out of bounds (max index is {num_neurons - 1}).")
        continue

    print(f"  Calculating tuning curve for Neuron {neuron_idx}...")
    mean_firing_rates_for_neuron = np.zeros(num_grating_conditions)

    for grating_idx in range(num_grating_conditions):
        spike_counts_all_trials_this_grating = []
        for trial_idx in range(num_trials_per_condition):
            spike_times_raw_cell = events_data[neuron_idx, grating_idx, trial_idx]
            if isinstance(spike_times_raw_cell, np.ndarray):
                spike_times_this_trial = spike_times_raw_cell.ravel()
            else:
                spike_times_this_trial = np.array([])

            spikes_in_window = spike_times_this_trial[
                (spike_times_this_trial >= analysis_window_start_time) &
                (spike_times_this_trial <= analysis_window_end_time)
            ]
            num_spikes_this_trial_in_window = len(spikes_in_window)
            spike_counts_all_trials_this_grating.append(num_spikes_this_trial_in_window)

        if spike_counts_all_trials_this_grating:
            avg_spike_count_this_grating = np.mean(spike_counts_all_trials_this_grating)
        else:
            avg_spike_count_this_grating = 0.0

        mean_firing_rates_for_neuron[grating_idx] = avg_spike_count_this_grating / analysis_duration

    # --- Plotting Section for the current neuron ---
    plt.figure(figsize=(10, 6))
    plt.plot(assumed_grating_orientations_degrees, mean_firing_rates_for_neuron, marker='o', linestyle='-', color='b')
    plt.xlabel("Assumed Stimulus Orientation (degrees)", fontsize=12)
    plt.ylabel("Mean Firing Rate (spikes/sec)", fontsize=12)
    plt.title(f"Orientation Tuning Curve for Neuron {neuron_idx} (Monkey 1, File: {os.path.basename(mat_file_path)})", fontsize=14)
    plt.xticks(assumed_grating_orientations_degrees, rotation=45)
    plt.yticks(fontsize=10)
    plt.ylim(bottom=0) # Ensure y-axis starts at 0 for firing rates
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.tight_layout()

    plot_filename = os.path.join(output_plot_directory, f"neuron_{neuron_idx}_tuning_curve.png")
    plt.savefig(plot_filename)
    # print(f"    Saved plot: {plot_filename}") # Optionally print for each save
    plt.close() # Close the figure to free up memory

print(f"\nFinished processing. Plots saved in '{output_plot_directory}' directory.")
print("Script finished.")